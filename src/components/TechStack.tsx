// ── Tooltip component ────────────────────────────────────────────────────────

type TooltipState = { visible: boolean; key: string };

const ToolTooltip = ({
  toolName,
  visible,
}: {
  toolName: string;
  visible: boolean;
}) => {
  const info = tooltipText[toolName];
  const [displayedLine1, setDisplayedLine1] = useState("");
  const [displayedLine2, setDisplayedLine2] = useState("");
  const [phase, setPhase] = useState<"idle" | "line1" | "line2" | "done">(
    "idle",
  );
  const timeoutRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  const clearAll = useCallback(() => {
    if (timeoutRef.current) clearTimeout(timeoutRef.current);
  }, []);

  useEffect(() => {
    if (!visible) {
      clearAll();
      setDisplayedLine1("");
      setDisplayedLine2("");
      setPhase("idle");
      return;
    }
    if (!info) return;

    setDisplayedLine1("");
    setDisplayedLine2("");
    setPhase("line1");
  }, [visible, toolName]);

  // Typewriter for line 1
  useEffect(() => {
    if (phase !== "line1" || !info) return;
    if (displayedLine1.length < info.line1.length) {
      timeoutRef.current = setTimeout(() => {
        setDisplayedLine1(info.line1.slice(0, displayedLine1.length + 1));
      }, 22);
    } else {
      setPhase("line2");
    }
    return clearAll;
  }, [phase, displayedLine1, info]);

  // Typewriter for line 2
  useEffect(() => {
    if (phase !== "line2" || !info) return;
    if (displayedLine2.length < info.line2.length) {
      timeoutRef.current = setTimeout(() => {
        setDisplayedLine2(info.line2.slice(0, displayedLine2.length + 1));
      }, 18);
    } else {
      setPhase("done");
    }
    return clearAll;
  }, [phase, displayedLine2, info]);

  if (!info) return null;

  return (
    <div className={`tool-tooltip${visible ? " tool-tooltip--visible" : ""}`}>
      <span className="tool-tooltip-name">{toolName}</span>
      <p className="tool-tooltip-line1">
        {displayedLine1}
        {phase === "line1" && <span className="tool-tooltip-cursor" />}
      </p>
      {(phase === "line2" || phase === "done") && (
        <p className="tool-tooltip-line2">
          {displayedLine2}
          {phase === "line2" && <span className="tool-tooltip-cursor" />}
        </p>
      )}
    </div>
  );
};

